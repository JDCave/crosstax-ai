"""Render PostgreSQL review SQL from ORM/migrations without connecting to a database."""

from __future__ import annotations

import argparse
import io
import runpy
from pathlib import Path

from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.operations import Operations
from alembic.script import ScriptDirectory
from sqlalchemy import Table, insert
from sqlalchemy.dialects.postgresql import dialect
from sqlalchemy.schema import CreateIndex, CreateSchema, CreateTable

from backend.models import Base

ROOT = Path(__file__).resolve().parents[2]
SQL_DIRECTORY = ROOT / "backend/infrastructure/db"
BASE_TABLES = frozenset(
    {
        "rule_sources",
        "rule_sync_runs",
        "rule_documents",
        "rule_versions",
        "rule_version_documents",
        "rule_engine_state",
    }
)


def rule_tables() -> list[Table]:
    """Exclude unrelated scaffold models even when another module imported them first."""
    return [
        table for table in Base.metadata.sorted_tables if table.schema == "crosstax" and table.name.startswith("rule_")
    ]


def normalize_sql(value: str) -> str:
    return "\n".join(line.rstrip() for line in value.strip().splitlines()) + "\n"


def render_tables(tables: list[Table], *, purpose: str, head: str) -> str:
    compiler = dialect()  # type: ignore[no-untyped-call]  # SQLAlchemy dialect factory is untyped.
    statements = [
        "-- GENERATED by: uv run python -m backend.cli.schema_sql --write",
        "-- Source: backend/models; do not edit this file manually.",
        f"-- {purpose}",
        f"-- ORM snapshot at Alembic revision {head}; review README.md before applying.",
        "-- PostgreSQL database: devdb; schema: crosstax. No existing tables are dropped or altered.",
        "BEGIN;",
        str(CreateSchema("crosstax", if_not_exists=True).compile(dialect=compiler)) + ";",
    ]
    for table in tables:
        statements.append(str(CreateTable(table).compile(dialect=compiler)).strip() + ";")
        for index in sorted(table.indexes, key=lambda item: str(item.name)):
            statements.append(str(CreateIndex(index).compile(dialect=compiler)) + ";")
    names = {table.name for table in tables}
    # Only initialize coordination rows; never invent rule sources, approved versions or audit data.
    for name, values in (
        ("rule_engine_state", {"id": 1}),
        ("rule_task_queue_state", {"id": 1, "generation": 0}),
    ):
        if name in names:
            table = Base.metadata.tables[f"crosstax.{name}"]
            statements.append(
                str(
                    insert(table)
                    .values(**values)
                    .compile(
                        dialect=compiler,
                        compile_kwargs={"literal_binds": True},
                    )
                )
                + ";"
            )
    statements.append("COMMIT;")
    return normalize_sql("\n\n".join(statements))


def render_task_migration(scripts: ScriptDirectory, revision_id: str = "20261108_rule_tasks") -> str:
    revision = scripts.get_revision(revision_id)
    if revision is None:
        raise ValueError("Task migration is missing")
    buffer = io.StringIO()
    context = MigrationContext.configure(dialect_name="postgresql", opts={"as_sql": True, "output_buffer": buffer})
    with Operations.context(context):
        runpy.run_path(revision.path)["upgrade"]()
    return normalize_sql(
        "-- GENERATED by: uv run python -m backend.cli.schema_sql --write\n"
        f"-- Source: Alembic {revision_id}; do not edit this file manually.\n"
        "-- Incremental review alternative, NOT an additional step after alembic upgrade.\n"
        "-- Connect to devdb; crosstax.rule_versions and prior migrations must exist.\n"
        "-- Manual SQL does not update alembic_version; see README.md.\n"
        "BEGIN;\n\n" + buffer.getvalue() + "\nCOMMIT;\n"
    )


def render_sql_files() -> dict[str, str]:
    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "alembic"))
    scripts = ScriptDirectory.from_config(config)
    head = scripts.get_current_head()
    if head is None:
        raise ValueError("Migration head is missing")
    tables = rule_tables()
    if not BASE_TABLES.issubset({table.name for table in tables}):
        raise ValueError("Baseline table contract is incomplete")
    return {
        "validation_engine.sql": render_tables(
            tables,
            purpose="FULL current rule-engine schema; use only for an empty schema or review.",
            head=head,
        ),
        "bootstrap_rules.sql": render_tables(
            [table for table in tables if table.name in BASE_TABLES],
            purpose="Six-table legacy baseline ONLY; follow with alembic upgrade head on a new database.",
            head=head,
        ),
        "rule_validation_tasks.sql": render_task_migration(scripts),
        "rule_pdf_reports.sql": render_task_migration(scripts, "20261108_pdf_reports"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Regenerate tracked SQL files; never executes SQL")
    mode.add_argument("--check", action="store_true", help="Fail on stale/missing SQL files (default)")
    args = parser.parse_args()
    stale = []
    for filename, content in render_sql_files().items():
        path = SQL_DIRECTORY / filename
        if args.write:
            path.write_text(content, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(filename)
    if stale:
        raise SystemExit("Stale SQL: " + ", ".join(stale) + "; run --write")
    print("Rule SQL regenerated" if args.write else "Rule SQL matches ORM and task migration")


if __name__ == "__main__":
    main()
